let a = 10;
let b = 3;

// Addition (+)
console.log(a + b);   // 13

// Subtraction (-)
console.log(a - b);   // 7

// Multiplication (*)
console.log(a * b);   // 30

// Exponentiation (**)
console.log(a ** b);  // 1000  (10³)

// Division (/)
console.log(a / b);   // 3.3333...

// Modulus (%)
console.log(a % b);   // 1  (remainder of 10 ÷ 3)

// Increment (++)
let c = 5;
console.log(c++);     // 5  (post-increment: returns THEN adds)
console.log(++c);     // 7  (pre-increment: adds THEN returns)

// Decrement (--)
let d = 5;
console.log(d--);     // 5  (post-decrement: returns THEN subtracts)
console.log(--d);     // 3  (pre-decrement: subtracts THEN returns)


